def esc(t):
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    return t.replace("\n", "&lt;br&gt;")


cells = []


def box(nid, label, x, y, w, h, style):
    cells.append('<mxCell id="%s" value="%s" style="%s" vertex="1" parent="1">'
                 '<mxGeometry x="%d" y="%d" width="%d" height="%d" as="geometry"/></mxCell>'
                 % (nid, esc(label), style, x, y, w, h))


def line(nid, x1, y1, x2, y2, style):
    cells.append('<mxCell id="%s" style="%s" edge="1" parent="1">'
                 '<mxGeometry relative="1" as="geometry">'
                 '<mxPoint x="%d" y="%d" as="sourcePoint"/>'
                 '<mxPoint x="%d" y="%d" as="targetPoint"/></mxGeometry></mxCell>'
                 % (nid, style, x1, y1, x2, y2))


