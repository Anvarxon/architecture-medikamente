BOX_W, BOX_H = 700, 200
CAT_H = 46


def draw(groups, up=True):
    for i, (name, causes) in enumerate(groups):
        x = 200 + i * 760
        if up:
            cat_y = 190
            box_y = cat_y + CAT_H + 10
            bone_from = (x + BOX_W // 2, box_y + BOX_H)
        else:
            box_y = SPINE_Y + 90
            cat_y = box_y + BOX_H + 10
            bone_from = (x + BOX_W // 2, box_y)
        box("cat%d%d" % (up, i), name, x, cat_y, BOX_W, CAT_H, CAT)
        box("cs%d%d" % (up, i), "\n".join("•  " + c for c in causes), x, box_y, BOX_W, BOX_H, CAUSE)
        spine_x = x + BOX_W // 2 + (260 if up else 260)
        line("bone%d%d" % (up, i), bone_from[0], bone_from[1], spine_x, SPINE_Y, BONE)


draw(TOP, up=True)
