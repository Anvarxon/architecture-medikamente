def band_row(p, s, d, y, label, ctl=False, up=False, **kw):
    xs = p.geo[s][0] + p.geo[s][2] // 2
    xd = p.geo[d][0] + p.geo[d][2] // 2
    an = (0.5, 0, 0.5, 0) if up else (0.5, 1, 0.5, 1)
    (p.ctl_edge if ctl else p.flow)(s, d, label, an=an, waypoints=[(xs, y), (xd, y)], **kw)


def band_col(p, s, d, x, label, ctl=False, left=False, **kw):
    ys = p.geo[s][1] + p.geo[s][3] // 2
    yd = p.geo[d][1] + p.geo[d][3] // 2
    an = (0, 0.5, 0, 0.5) if left else (1, 0.5, 1, 0.5)
    (p.ctl_edge if ctl else p.flow)(s, d, label, an=an, waypoints=[(x, ys), (x, yd)], **kw)


